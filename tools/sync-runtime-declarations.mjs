import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const argument = (name, fallback) => {
    const at = args.indexOf(name);
    assert(at < 0 || args[at + 1], `${name} requires a directory`);
    return resolve(at < 0 ? fallback : args[at + 1]);
};
const node = argument('--node', resolve(root, '../AutoJs6-Plugin-NodeJs-Runtime'));
const bun = argument('--bun', resolve(root, '../AutoJs6-Plugin-Bun-Runtime'));
const ace = args.includes('--ace') ? argument('--ace', '') : null;
const normalize = text => text.replace(/^\uFEFF/, '').replace(/\r\n?/g, '\n');
const digest = text => createHash('sha256').update(text).digest('hex');
const sources = new Map();
const filesBelow = directory => readdirSync(directory, { withFileTypes: true }).flatMap(entry =>
    entry.isDirectory() ? filesBelow(resolve(directory, entry.name)) : [resolve(directory, entry.name)]).sort();
const nodeSource = resolve(node, 'docs/nodejs/types/autojs6-node');
for (const file of filesBelow(nodeSource).filter(file => file.endsWith('.d.ts'))) {
    const name = relative(nodeSource, file).replace(/\\/g, '/');
    sources.set(`autojs6-node/${name}`, normalize(readFileSync(file, 'utf8')));
}
const bunSource = normalize(readFileSync(resolve(bun, 'app/src/main/assets/autojs6/host-client.d.mts'), 'utf8'));
sources.set('autojs6-bun/host-client.d.mts', bunSource);
// This ambient name is a type-only editor alias. The actual module is loaded from
// AUTOJS6_HOST_CLIENT_MODULE; no runtime package named autojs6:bun-host is implied.
sources.set('autojs6-bun/index.d.ts', [
    '// Generated by tools/sync-runtime-declarations.mjs. Do not edit.',
    '// Type-only alias. Load the executable module from AUTOJS6_HOST_CLIENT_MODULE.',
    'declare module "autojs6:bun-host" {',
    bunSource.replace(/^export declare /gm, 'export ').split('\n').map(line => line ? `    ${line}` : '').join('\n'),
    '}', '',
].join('\n'));

const manifest = {
    schema: 1,
    sources: {
        node: 'AutoJs6-Plugin-NodeJs-Runtime/docs/nodejs/types/autojs6-node',
        bun: 'AutoJs6-Plugin-Bun-Runtime/app/src/main/assets/autojs6/host-client.d.mts',
    },
    files: Object.fromEntries([...sources].map(([name, text]) => [name, digest(text)])),
};
sources.set('runtime-declarations.json', JSON.stringify(manifest, null, 2) + '\n');
const targets = [resolve(root, 'declarations')];
if (ace) {
    const lock = JSON.parse(readFileSync(resolve(ace, 'tools/ace-lsp/ace-builds-lock.json'), 'utf8'));
    targets.push(resolve(ace, lock.assetRoot, 'autojs6/types'));
}
let changed = 0;
for (const target of targets) {
    for (const [name, text] of sources) {
        const file = resolve(target, name);
        if (existsSync(file) && normalize(readFileSync(file, 'utf8')) === text) continue;
        changed++;
        if (check) continue;
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, text);
    }
    for (const folder of ['autojs6-node', 'autojs6-bun']) {
        const directory = resolve(target, folder);
        if (!existsSync(directory)) continue;
        for (const file of filesBelow(directory)) {
            const name = relative(directory, file).replace(/\\/g, '/');
            if (sources.has(`${folder}/${name}`)) continue;
            assert(/\.d\.(?:ts|mts)$/.test(name), `Unexpected managed declaration: ${folder}/${name}`);
            changed++;
            if (!check) rmSync(file);
        }
    }
}
if (ace) {
    const file = resolve(targets[1], 'autojs6/package.json');
    const text = normalize(readFileSync(resolve(root, 'package.json'), 'utf8'));
    if (!existsSync(file) || normalize(readFileSync(file, 'utf8')) !== text || readFileSync(file, 'utf8').includes('\r')) {
        changed++;
        if (!check) writeFileSync(file, text);
    }
    // The AutoJs6 host's tools/ace-completion/import-autojs6-dts.mjs writes BUNDLED_DECLARATIONS.md.
    // package.json is also copied here, so keep the version it records in step.
    const notes = resolve(targets[1], 'autojs6/BUNDLED_DECLARATIONS.md');
    assert(existsSync(notes), `${notes} is missing; run the AutoJs6 host's tools/ace-completion/import-autojs6-dts.mjs`);
    const recorded = readFileSync(notes, 'utf8');
    assert(/^- Version: .*$/m.test(recorded), `${notes} has no "- Version:" line`);
    const versioned = recorded.replace(/^- Version: .*$/m, `- Version: ${JSON.parse(text).version}`);
    if (versioned !== recorded) {
        changed++;
        if (!check) writeFileSync(notes, versioned);
    }
}
assert(!check || changed === 0, `${changed} runtime declaration files are stale; run the sync command without --check`);
console.log(JSON.stringify({ checked: check, targets: targets.length, declarations: sources.size - 1, changed }));
